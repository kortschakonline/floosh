/// Passt einen Logo-Pfad seitenverhältnistreu und zentriert in `rect` ein.
private func fitTransform(design: CGRect, into rect: CGRect) -> (CGPoint) -> CGPoint {
    let scale = min(rect.width / design.width, rect.height / design.height)
    let dx = rect.midX - design.midX * scale
    let dy = rect.midY - design.midY * scale
    return { CGPoint(x: $0.x * scale + dx, y: $0.y * scale + dy) }
}

/// Der floosh-Doppel-Blitz. `.frame` ist die adaptive Hälfte,
/// `.accent` die orange.
struct FlooshBoltShape: Shape {
    enum Part { case frame, accent }
    var part: Part

    func path(in rect: CGRect) -> Path {
        let t = fitTransform(design: LogoPaths.boltDesign, into: rect)
        switch part {
        case .frame: return LogoPaths.boltFrame(t: t)
        case .accent: return LogoPaths.boltAccent(t: t)
        }
    }
}

/// Die solide floosh-Wortmarke: großer Blitz + gefüllte FLOOSH-Lettern.
/// Bleibt im Gegensatz zur Outline-Variante auch klein knackig lesbar.
struct FlooshLockupShape: Shape {
    enum Part { case frame, accent, letters }
    var part: Part

    func path(in rect: CGRect) -> Path {
        let t = fitTransform(design: LogoPaths.logoDesign, into: rect)
        switch part {
        case .frame: return LogoPaths.logoFrame(t: t)
        case .accent: return LogoPaths.logoAccent(t: t)
        case .letters: return LogoPaths.logoLetters(t: t)
        }
    }
}

/// Die Outline-Wortmarke mit den Stoppuhr-Ringen als „oo" — für große
/// Einsätze; bei UI-Größen die solide `FlooshLockupShape` verwenden.
/// `.rings` ist als Kontur angelegt und wird gestrichen, nicht gefüllt.
struct FlooshWordmarkShape: Shape {
    enum Part { case frame, accent, letters, rings }
    var part: Part

    func path(in rect: CGRect) -> Path {
        let t = fitTransform(design: LogoPaths.markDesign, into: rect)
        switch part {
        case .frame: return LogoPaths.markFrame(t: t)
        case .accent: return LogoPaths.markAccent(t: t)
        case .letters: return LogoPaths.markLetters(t: t)
        case .rings: return LogoPaths.markRings(t: t)
        }
    }
}

/// Die JRN.digital-Wortmarke (Mini-Variante). `.primary` sind die Buchstaben,
/// `.accent` die zwei gelben Quadrate.
struct JRNLogoShape: Shape {
    enum Part { case primary, accent }
    var part: Part

    func path(in rect: CGRect) -> Path {
        let t = fitTransform(design: LogoPaths.jrnDesign, into: rect)
        switch part {
        case .primary: return LogoPaths.jrnPrimary(t: t)
        case .accent: return LogoPaths.jrnAccent(t: t)
        }
    }
}

// MARK: - Views

/// Konkrete Logo-Zeichenfarbe statt `.primary`: Vibrancy auf Liquid Glass
/// dunkelt `.primary` stark ab (Logos kaum sichtbar). Weiches Weiß bzw.
/// Anthrazit — bewusst nicht rein weiß/schwarz, damit nichts „leuchtet".
private func logoInk(for scheme: ColorScheme) -> Color {
    scheme == .dark ? Color(white: 0.88) : Color(white: 0.16)
}

/// Das floosh-Logo: der Doppel-Blitz aus dem Marken-SVG.
/// Die vordere Hälfte folgt der Logo-Tinte, die hintere bleibt Marken-Orange.
struct FlooshLogo: View {
    /// Höhe in Punkten.
    var size: CGFloat = 16
    @Environment(\.colorScheme) private var colorScheme

    var body: some View {
        ZStack {
            FlooshBoltShape(part: .frame)
                .fill(logoInk(for: colorScheme))
            FlooshBoltShape(part: .accent)
                .fill(Color.flooshOrange)
                .shadow(color: .flooshOrange.opacity(0.55), radius: size * 0.12)
        }
        .aspectRatio(LogoPaths.boltDesign.width / LogoPaths.boltDesign.height,
                     contentMode: .fit)
        .frame(height: size)
    }
}

/// Die floosh-Wortmarke (solide Variante: Blitz + gefülltes FLOOSH).
struct FlooshWordmark: View {
    /// Höhe in Punkten.
    var height: CGFloat = 16
    @Environment(\.colorScheme) private var colorScheme

    var body: some View {
